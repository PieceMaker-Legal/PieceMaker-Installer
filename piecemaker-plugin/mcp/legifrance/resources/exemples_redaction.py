EXEMPLES_DISCUSSION = """
# EXEMPLES DE RÉDACTION - DISCUSSION

## EXEMPLE 1 : Responsabilité contractuelle

### Sur la demande de restitution du dépôt de garantie

**En droit**

Aux termes de l'article 1304-3 du Code civil :
« La condition suspensive est réputée accomplie si celui qui y avait intérêt en a empêché l'accomplissement. »

L'article 1186 du Code civil dispose par ailleurs :
« Un contrat valablement formé devient caduc si l'un de ses éléments essentiels disparaît. »

La Cour de cassation a rappelé que le vendeur ne peut conserver le dépôt de garantie lorsque la condition suspensive d'obtention de prêt a régulièrement défailli (Cass. civ. 3ème, 12 janvier 2017, n° 15-27.155).

**En fait**

En l'espèce, Monsieur DUPONT a régulièrement notifié la non-obtention de son prêt dans le délai contractuel (Pièce n°2).

L'attestation de la Banque Populaire démontre que le refus de prêt est motivé par des raisons objectives tenant à la situation financière de l'emprunteur (Pièce n°3).

Monsieur DUPONT n'a commis aucune faute dans l'accomplissement de ses démarches de financement.

La société IMMOBILIA ne peut donc opposer aucun motif légitime au refus de restitution du dépôt de garantie.

**Par conséquent**, il est demandé au Tribunal judiciaire de Paris de condamner la société IMMOBILIA à restituer à Monsieur DUPONT la somme de 45.000 € au titre du dépôt de garantie.

---

## EXEMPLE 2 : Résiliation de bail et expulsion

### Sur l'acquisition de la clause résolutoire

**En droit**

Aux termes de l'article 24 de la loi n° 89-462 du 6 juillet 1989 :
« Toute clause prévoyant la résiliation de plein droit du contrat de location pour défaut de paiement du loyer ou des charges aux termes convenus [...] ne produit effet que deux mois après un commandement de payer demeuré infructueux. »

**En fait**

En l'espèce, le bail signé le 1er janvier 2020 comporte une clause résolutoire en son article 8 (Pièce n°1, page 4).

Un commandement de payer a été délivré le 15 mai 2023 visant expressément cette clause (Pièce n°4).

Ce commandement est demeuré sans effet, le délai de deux mois ayant expiré le 15 juillet 2023 sans régularisation.

**Par conséquent**, il est demandé au Tribunal judiciaire de Nanterre de constater l'acquisition de la clause résolutoire et de prononcer la résiliation du bail.

### Sur la demande d'expulsion

**En droit**

L'article L. 411-1 du Code des procédures civiles d'exécution dispose :
« Sauf disposition spéciale, l'expulsion d'un immeuble ou d'un lieu habité ne peut être poursuivie qu'en vertu d'une décision de justice. »

**En fait**

La clause résolutoire ayant été acquise, Madame BERNARD est devenue occupante sans droit ni titre des lieux loués.

**Par conséquent**, il est demandé au Tribunal d'ordonner l'expulsion de Madame BERNARD et de tous occupants de son chef, au besoin avec le concours de la force publique.
"""

